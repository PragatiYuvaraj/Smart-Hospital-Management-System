'use strict';

// Credentials in this test are synthetic fixtures only; never use demo or production account values.
const assert = require('assert');
const mongoose = require('mongoose');
const User = require('../src/models/User');
const Patient = require('../src/models/Patient');
const AuditLog = require('../src/models/AuditLog');
const { registerPatient } = require('../src/services/auth.service');

const originalMethods = {
  userFindOne: User.findOne,
  userSave: User.prototype.save,
  userUpdateOne: User.updateOne,
  userDeleteOne: User.deleteOne,
  patientSave: Patient.prototype.save,
  patientDeleteOne: Patient.deleteOne,
  auditSave: AuditLog.prototype.save,
  connectionTransaction: Object.getOwnPropertyDescriptor(mongoose.connection, 'transaction')
};

const users = new Map();
const patients = new Map();
const auditLogs = [];
let patientSaveError = null;
let failAuditSave = false;
const saveSessions = [];
const auditSaveSessions = [];
let passed = 0;
let failed = 0;

const assertTest = (condition, description) => {
  if (condition) {
    passed++;
    console.log(`  PASS: ${description}`);
  } else {
    failed++;
    console.error(`  FAIL: ${description}`);
  }
};

const resetData = () => {
  users.clear();
  patients.clear();
  auditLogs.length = 0;
  patientSaveError = null;
  failAuditSave = false;
  saveSessions.length = 0;
  auditSaveSessions.length = 0;
};

User.findOne = async ({ email }) =>
  Array.from(users.values()).find((user) => user.email === email) || null;

User.prototype.save = async function (options = {}) {
  saveSessions.push(options.session || null);
  users.set(String(this._id), this);
  return this;
};

User.updateOne = async ({ _id }, update) => {
  const user = users.get(String(_id));
  if (user) {
    Object.assign(user, update.$set);
  }
  return { acknowledged: true, matchedCount: user ? 1 : 0 };
};

User.deleteOne = async ({ _id }) => ({
  acknowledged: true,
  deletedCount: users.delete(String(_id)) ? 1 : 0
});

Patient.prototype.save = async function (options = {}) {
  saveSessions.push(options.session || null);
  if (patientSaveError) {
    throw patientSaveError;
  }
  patients.set(String(this.userId), this);
  return this;
};

const deletePatientProfile = async ({ userId }) => ({
  acknowledged: true,
  deletedCount: patients.delete(String(userId)) ? 1 : 0
});
Patient.deleteOne = deletePatientProfile;

AuditLog.prototype.save = async function (options = {}) {
  if (failAuditSave) {
    throw new Error('Simulated audit persistence failure');
  }
  auditLogs.push(this);
  auditSaveSessions.push(options.session || null);
  return this;
};

const register = (overrides = {}) =>
  registerPatient({
    name: 'Demo Patient',
    email: 'demo.patient@example.test',
    password: 'Patient@2026',
    dateOfBirth: '1990-04-12',
    ...overrides
  });

const runTests = async () => {
  try {
    console.log('\n--- Patient registration and profile creation ---');

    resetData();
    const result = await register({
      role: 'DOCTOR',
      permissions: ['DUTY_DOCTOR'],
      userId: 'client-user-id',
      patientNumber: 'CLIENT-PATIENT-NUMBER'
    });
    const createdUser = Array.from(users.values())[0];
    const createdPatient = Array.from(patients.values())[0];

    assertTest(result.user.role === 'PATIENT', 'Registration always assigns the PATIENT role');
    assertTest(result.user.permissions.length === 0, 'Client-supplied permissions are ignored');
    assertTest(
      String(createdPatient.userId) === String(createdUser._id),
      'Patient profile links to the newly created user'
    );
    assertTest(
      /^PAT-[0-9A-F]{16}$/.test(createdPatient.patientNumber) &&
        createdPatient.patientNumber !== 'CLIENT-PATIENT-NUMBER',
      'Patient number is generated by the server'
    );
    assertTest(
      !Object.prototype.hasOwnProperty.call(result.user, 'passwordHash'),
      'Password hash is absent from the registration response'
    );
    assertTest(Boolean(result.token), 'Registration returns the existing JWT response data');
    assertTest(
      auditLogs.length === 1 &&
        auditLogs[0].action === 'PATIENT_REGISTERED' &&
        String(auditLogs[0].actorId) === String(createdUser._id) &&
        String(auditLogs[0].resourceId) === String(createdPatient._id) &&
        auditLogs[0].outcome === 'SUCCESS',
      'Registration logs the authenticated patient and new profile'
    );
    const auditFields = auditLogs[0].toObject();
    assertTest(
      !['password', 'passwordHash', 'token', 'name', 'email', 'dateOfBirth'].some(
        (field) => Object.prototype.hasOwnProperty.call(auditFields, field)
      ),
      'Registration audit entry excludes credentials and personal details'
    );

    resetData();
    const doctorAttempt = await register({
      email: 'role.doctor@example.test',
      role: 'DOCTOR'
    });
    assertTest(doctorAttempt.user.role === 'PATIENT', 'DOCTOR role override attempt stays PATIENT');

    resetData();
    const pharmacyAttempt = await register({
      email: 'role.pharmacy@example.test',
      role: 'PHARMACY'
    });
    assertTest(pharmacyAttempt.user.role === 'PATIENT', 'PHARMACY role override attempt stays PATIENT');

    let duplicateError;
    try {
      await register({ email: 'role.pharmacy@example.test' });
    } catch (error) {
      duplicateError = error;
    }
    assertTest(
      duplicateError && duplicateError.statusCode === 409,
      'Duplicate email registration returns HTTP 409'
    );

    resetData();
    patientSaveError = new Error('Simulated patient profile write failure');
    let profileFailure;
    try {
      await register({ email: 'profile.failure@example.test' });
    } catch (error) {
      profileFailure = error;
    }
    assertTest(Boolean(profileFailure), 'Patient profile creation failure rejects registration');
    assertTest(
      profileFailure.message === 'Patient registration could not be completed.',
      'Unexpected database errors do not expose internal details'
    );
    assertTest(
      users.size === 0 && patients.size === 0,
      'Failed profile creation rolls back the inactive account'
    );
    assertTest(auditLogs.length === 0, 'Failed registration creates no success audit entry');

    resetData();
    failAuditSave = true;
    let auditFailure;
    try {
      await register({ email: 'audit.failure@example.test' });
    } catch (error) {
      auditFailure = error;
    }
    assertTest(
      auditFailure &&
        auditFailure.statusCode === 500 &&
        auditFailure.message.includes('Audit logging failed'),
      'Audit persistence failure is surfaced to the caller'
    );
    assertTest(
      users.size === 0 && patients.size === 0 && auditLogs.length === 0,
      'Failed registration audit rolls back standalone registration'
    );

    resetData();
    patientSaveError = new Error('Simulated patient profile write failure');
    Patient.deleteOne = async () => {
      throw new Error('Simulated cleanup failure');
    };
    let cleanupFailure;
    try {
      await register({ email: 'cleanup.failure@example.test' });
    } catch (error) {
      cleanupFailure = error;
    }
    const remainingUser = Array.from(users.values())[0];
    assertTest(
      cleanupFailure && cleanupFailure.cleanupErrors && cleanupFailure.cleanupErrors.length > 0,
      'Incomplete rollback is surfaced explicitly'
    );
    assertTest(
      remainingUser && remainingUser.status === 'INACTIVE',
      'An account left after cleanup failure remains inactive'
    );
    Patient.deleteOne = deletePatientProfile;

    resetData();
    patientSaveError = Object.assign(new Error('Duplicate profile identifier'), {
      code: 11000,
      keyPattern: { patientNumber: 1 }
    });
    let duplicateProfileError;
    try {
      await register({ email: 'duplicate.profile@example.test' });
    } catch (error) {
      duplicateProfileError = error;
    }
    assertTest(
      duplicateProfileError && duplicateProfileError.statusCode === 409,
      'Duplicate patient profile identifiers return HTTP 409'
    );

    resetData();
    const originalReadyState = Object.getOwnPropertyDescriptor(mongoose.connection, 'readyState');
    const originalClient = Object.getOwnPropertyDescriptor(mongoose.connection, 'client');
    const originalTransaction = Object.getOwnPropertyDescriptor(mongoose.connection, 'transaction');
    let transactionUsed = false;
    const transactionSession = {
      withTransaction: async (operation) => {
        transactionUsed = true;
        await operation();
      },
      endSession: async () => {}
    };
    Object.defineProperty(mongoose.connection, 'readyState', {
      configurable: true,
      value: 1
    });
    Object.defineProperty(mongoose.connection, 'client', {
      configurable: true,
      value: { topology: { description: { type: 'ReplicaSetWithPrimary' } } }
    });
    Object.defineProperty(mongoose.connection, 'transaction', {
      configurable: true,
      value: async (operation) =>
        transactionSession.withTransaction(() => operation(transactionSession))
    });
    try {
      await register({ email: 'transaction@example.test' });
    } finally {
      if (originalReadyState) {
        Object.defineProperty(mongoose.connection, 'readyState', originalReadyState);
      } else {
        delete mongoose.connection.readyState;
      }
      if (originalClient) {
        Object.defineProperty(mongoose.connection, 'client', originalClient);
      } else {
        delete mongoose.connection.client;
      }
      if (originalTransaction) {
        Object.defineProperty(mongoose.connection, 'transaction', originalTransaction);
      } else {
        delete mongoose.connection.transaction;
      }
    }
    assertTest(transactionUsed, 'Replica-set topology uses a MongoDB transaction');
    assertTest(
      saveSessions.filter((session) => session === transactionSession).length === 2,
      'User and patient writes share the transaction session'
    );
    assertTest(
      auditSaveSessions.filter((session) => session === transactionSession).length === 1,
      'Registration audit entry shares the transaction session'
    );

    let missingDateError;
    try {
      await register({ email: 'missing.dob@example.test', dateOfBirth: undefined });
    } catch (error) {
      missingDateError = error;
    }
    assertTest(
      missingDateError && missingDateError.statusCode === 400,
      'Missing required date of birth is rejected'
    );
  } finally {
    User.findOne = originalMethods.userFindOne;
    User.prototype.save = originalMethods.userSave;
    User.updateOne = originalMethods.userUpdateOne;
    User.deleteOne = originalMethods.userDeleteOne;
    Patient.prototype.save = originalMethods.patientSave;
    Patient.deleteOne = originalMethods.patientDeleteOne;
    AuditLog.prototype.save = originalMethods.auditSave;
    if (originalMethods.connectionTransaction) {
      Object.defineProperty(
        mongoose.connection,
        'transaction',
        originalMethods.connectionTransaction
      );
    } else {
      delete mongoose.connection.transaction;
    }
  }

  console.log(`\nRegistration assertions: ${passed + failed} | Passed: ${passed} | Failed: ${failed}\n`);
  if (failed > 0) {
    process.exitCode = 1;
  }
};

runTests().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
