/**
 * set-env.js — Build-time Angular environment injector
 *
 * Reads the BACKEND_URL Vercel environment variable and writes
 * src/environments/environment.prod.ts before the Angular CLI build runs.
 *
 * Usage (Vercel custom build command for the frontend project):
 *   node scripts/set-env.js && npx ng build --configuration production
 *
 * Required Vercel environment variable:
 *   BACKEND_URL  — The full base URL of the deployed backend project.
 *                  Example: https://smart-hospital-backend.vercel.app
 *                  Do NOT include a trailing slash or /api suffix.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const backendUrl = process.env.BACKEND_URL;

if (!backendUrl || !backendUrl.trim()) {
  console.error('');
  console.error('[set-env] ✗ BACKEND_URL is not set.');
  console.error('[set-env]   Add it to the Vercel frontend project environment variables.');
  console.error('[set-env]   Example value: https://smart-hospital-backend.vercel.app');
  console.error('');
  process.exit(1);
}

// Strip trailing slash; append /api path prefix
const normalised = backendUrl.trim().replace(/\/+$/, '');
const apiUrl = `${normalised}/api`;

const content = `// AUTO-GENERATED by scripts/set-env.js — do not edit manually.
// The apiUrl value is set at build time from the BACKEND_URL Vercel
// environment variable on the frontend project.
// See: frontend/scripts/set-env.js
export const environment = {
  production: true,
  apiUrl: '${apiUrl}'
};
`;

const outPath = path.resolve(__dirname, '..', 'src', 'environments', 'environment.prod.ts');
fs.writeFileSync(outPath, content, 'utf8');

console.log('[set-env] ✓ environment.prod.ts written.');
console.log('[set-env]   apiUrl →', apiUrl);
